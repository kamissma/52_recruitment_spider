def normalize_city(city):
    """将城市字符串规范化为 CITY_COORDS 中的标准键名"""
    if not city:  # 空值直接返回空串
        return ''
    city = city.strip().replace('市', '')  # 去空白并去掉「市」后缀
    for key in CITY_COORDS:  # 与已知城市键模糊匹配
        if key in city or city in key:  # 包含关系即视为同一城市
            return key
    return city  # 无匹配则返回处理后的原字符串


def to_geo_province(province):
    """将省份简称转为 ECharts GeoJSON 使用的全称"""
    return PROVINCE_GEO_NAMES.get(province, province)  # 有映射用全称，否则原样返回
